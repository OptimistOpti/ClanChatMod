package com.optimistopti.clanchat.chat;

public enum AttachmentType {
	/** Координаты (текущая позиция игрока или выбранная точка/маячок клана). */
	COORDINATES,
	/** Предмет, который игрок держит в руке в момент отправки. */
	HELD_ITEM,
	/** Снапшот всего инвентаря (36 слотов + броня + офхенд). */
	INVENTORY,
	/** Снапшот эндер-сундука (27 слотов). */
	ENDER_CHEST,
	/** Текущее здоровье/броня/эффекты — обычно с авто-пингом "нужна помощь". */
	HEALTH_STATUS
}
