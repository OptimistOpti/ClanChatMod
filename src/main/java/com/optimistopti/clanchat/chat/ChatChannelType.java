package com.optimistopti.clanchat.chat;

public enum ChatChannelType {
	/** Общий чат клана — видят все участники. */
	CLAN,
	/** Чат для офицеров и лидера. */
	OFFICERS,
	/** Личное сообщение конкретному игроку (в рамках того же клана либо приглашение). */
	WHISPER,
	/** Системные сообщения (вступление/кик/повышение и т.д.), не отправляются игроками напрямую. */
	SYSTEM
}
